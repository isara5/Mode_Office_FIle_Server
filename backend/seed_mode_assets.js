async function columnExists(conn, tableName, columnName) {
  const [rows] = await conn.query(
    "SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ? AND COLUMN_NAME = ? LIMIT 1",
    [tableName, columnName]
  );
  return rows.length > 0;
}

async function runMigrationAndSeed() {
  console.log("Connecting to database...");
  const conn = await db.getConnection();

  try {
    console.log("1. Ensuring all required columns exist in `assets` table...");

    const columnDefs = [
      { name: "equipment_category", type: "VARCHAR(100) NULL" },
      { name: "equipment_name", type: "VARCHAR(255) NULL" },
      { name: "brand", type: "VARCHAR(255) NULL" },
      { name: "model", type: "VARCHAR(255) NULL" },
      { name: "asset_tag_number", type: "VARCHAR(100) NULL" },
      { name: "processor", type: "VARCHAR(255) NULL" },
      { name: "storage", type: "VARCHAR(100) NULL" },
      { name: "ram", type: "VARCHAR(100) NULL" },
      { name: "operating_system", type: "VARCHAR(100) NULL" },
      { name: "ip_address", type: "VARCHAR(100) NULL" },
      { name: "division", type: "VARCHAR(100) NULL" },
      { name: "assigned_officer", type: "VARCHAR(255) NULL" },
      { name: "designation", type: "VARCHAR(100) NULL" },
      { name: "equipment_condition", type: "VARCHAR(100) NULL" },
      { name: "operational_status", type: "VARCHAR(100) NULL" },
      { name: "remarks", type: "TEXT NULL" },
      { name: "qr_code_data", type: "TEXT NULL" },
      { name: "qr_code_path", type: "VARCHAR(255) NULL" },
    ];

    for (const col of columnDefs) {
      const exists = await columnExists(conn, 'assets', col.name);
      if (!exists) {
        console.log(`Adding column \`${col.name}\`...`);
        await conn.query(`ALTER TABLE assets ADD COLUMN \`${col.name}\` ${col.type}`);
      }
    }

    console.log("2. Generating QR Codes and Inserting 73 Assets into database...");
    let insertedCount = 0;

    for (const item of assetsData) {
      // Build safe filename for QR code
      const safeId = item.asset_id.replace(/[^a-zA-Z0-9_-]/g, "_");
      const qrFileName = `qr_${safeId}.png`;
      const qrFilePath = path.join(qrcodeDir, qrFileName);
      const relativeQrPath = `uploads/qrcodes/${qrFileName}`;

      // Detailed QR Code JSON payload preserving exact Serial Number and identifiers
      const qrPayload = JSON.stringify({
        org: "Ministry of Digital Economy (MoDE)",
        asset_id: item.asset_id,
        serial_number: item.serial_number,
        asset_tag: item.asset_tag_number,
        category: item.equipment_category,
        name: item.equipment_name,
        brand: item.brand,
        model: item.model,
        specs: {
          processor: item.processor,
          ram: item.ram,
          storage: item.storage,
          os: item.operating_system,
          ip: item.ip_address
        },
        division: item.division,
        assigned_officer: item.assigned_officer,
        designation: item.designation,
        condition: item.equipment_condition,
        status: item.operational_status,
        remarks: item.remarks
      }, null, 2);

      // Generate QR Code PNG image
      await QRCode.toFile(qrFilePath, qrPayload, {
        errorCorrectionLevel: 'M',
        type: 'png',
        margin: 2,
        width: 350,
        color: {
          dark: '#1e1b4b', // deep indigo
          light: '#ffffff'
        }
      });

      // Composite asset_name for backward compatibility with existing UI
      const brandStr = item.brand && item.brand !== '-' ? item.brand : '';
      const modelStr = item.model && item.model !== '-' ? item.model : '';
      const nameComposite = [brandStr, modelStr].filter(Boolean).join(' ') || item.equipment_name;

      // Status mapping for standard UI tags
      let statusMapped = item.operational_status;
      if (item.operational_status.toLowerCase() === 'in use') {
        statusMapped = 'In Use';
      } else if (item.operational_status.toLowerCase() === 'repair' || item.operational_status.toLowerCase() === 'broken') {
        statusMapped = 'Maintenance';
      } else if (item.operational_status.toLowerCase() === 'unpack') {
        statusMapped = 'Available';
      } else if (item.operational_status.toLowerCase() === 'no use') {
        statusMapped = 'Available';
      }

      // Insert or Update Asset
      await conn.query(
        `INSERT INTO assets (
          asset_id, asset_name, description, category, serial_id, status,
          equipment_category, equipment_name, brand, model, asset_tag_number,
          processor, storage, ram, operating_system, ip_address, division,
          assigned_officer, designation, equipment_condition, operational_status,
          remarks, qr_code_data, qr_code_path
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON DUPLICATE KEY UPDATE
          asset_name = VALUES(asset_name),
          category = VALUES(category),
          serial_id = VALUES(serial_id),
          status = VALUES(status),
          equipment_category = VALUES(equipment_category),
          equipment_name = VALUES(equipment_name),
          brand = VALUES(brand),
          model = VALUES(model),
          asset_tag_number = VALUES(asset_tag_number),
          processor = VALUES(processor),
          storage = VALUES(storage),
          ram = VALUES(ram),
          operating_system = VALUES(operating_system),
          ip_address = VALUES(ip_address),
          division = VALUES(division),
          assigned_officer = VALUES(assigned_officer),
          designation = VALUES(designation),
          equipment_condition = VALUES(equipment_condition),
          operational_status = VALUES(operational_status),
          remarks = VALUES(remarks),
          qr_code_data = VALUES(qr_code_data),
          qr_code_path = VALUES(qr_code_path),
          updated_at = CURRENT_TIMESTAMP`,
        [
          item.asset_id,
          nameComposite,
          `${item.equipment_name} - ${item.division} (${item.assigned_officer})`,
          item.equipment_category,
          item.serial_number,
          statusMapped,
          item.equipment_category,
          item.equipment_name,
          item.brand,
          item.model,
          item.asset_tag_number,
          item.processor,
          item.storage,
          item.ram,
          item.operating_system,
          item.ip_address,
          item.division,
          item.assigned_officer,
          item.designation,
          item.equipment_condition,
          item.operational_status,
          item.remarks,
          qrPayload,
          relativeQrPath
        ]
      );

      insertedCount++;
    }

    console.log(`\n🎉 Successfully imported and generated QR codes for ${insertedCount} assets!`);

    // Verify count in database
    const [[{ total }]] = await conn.query("SELECT COUNT(*) as total FROM assets");
    console.log(`Total Assets now in DB: ${total}`);

    // Division breakdown in DB
    const [breakdown] = await conn.query("SELECT division, COUNT(*) as count FROM assets GROUP BY division");
    console.log("\nDivision Summary:");
    console.table(breakdown);

  } catch (error) {
    console.error("Migration/Seeding Error:", error);
    throw error;
  } finally {
    conn.release();
    process.exit(0);
  }
}

runMigrationAndSeed();

